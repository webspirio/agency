def build() -> list[dict]:
    cases: list[dict] = []

    for op in ("add", "sub", "mul"):
        for a in CORE:
            for b in CORE:
                cases.append(binary(op, a, b, 2))
        for a in CROSS:
            for b in CROSS:
                for scale in (0, 4):
                    cases.append(binary(op, a, b, scale))

    for a in DIVIDENDS:
        for n in DIVISORS:
            for scale in (2, 4):
                cases.append(div(a, n, scale))
    for a in ("0.005", "2.50", "-2.50", "126.40"):
        for n in (1, 2, -2, 3):
            cases.append(div(a, n, 0))

    for a in ROUNDABLE:
        for scale in (0, 1, 2, 3, 4, 6):
            cases.append(rnd(a, scale))

    for values in SUM_LINES:
        for scale in (0, 2, 4):
            cases.append(summation(values, scale))

    for a in CORE:
        for b in CORE:
            cases.append(compare(a, b))

    for op in ("gt", "gte", "lt", "lte"):
        for a in RELATIONAL:
            for b in RELATIONAL:
                cases.append(relation(op, a, b))

    for op in ("isZero", "isNegative"):
        for a in ROUNDABLE:
            cases.append(predicate(op, a))

    # Hand-derived rows last, each checked against CPython before it is written.
    for op, a, b, scale, expected in HAND_DERIVED:
        case = binary(op, a, b, scale)
        assert case["expected"] == expected, f"{op}({a},{b},{scale}) -> {case['expected']} != {expected}"
        cases.append(case)
    for a, n, scale, expected in HAND_DERIVED_DIV:
        case = div(a, n, scale)
        assert case["expected"] == expected, f"div({a},{n},{scale}) -> {case['expected']} != {expected}"
        cases.append(case)
    for values, scale, expected in HAND_DERIVED_SUM:
        case = summation(values, scale)
        assert case["expected"] == expected, f"sum({values},{scale}) -> {case['expected']} != {expected}"
        cases.append(case)
    for a, b, expected in HAND_DERIVED_CMP:
        case = compare(a, b)
        assert case["expected"] == expected, f"cmp({a},{b}) -> {case['expected']} != {expected}"
        cases.append(case)

    # De-duplicate on the full case identity, preserving first-seen order.
    seen: set[str] = set()
    unique: list[dict] = []
    for case in cases:
        key = json.dumps(case, sort_keys=True)
        if key not in seen:
            seen.add(key)
            unique.append(case)
    return unique


def main() -> None:
    with localcontext() as ctx:
        ctx.prec = PRECISION
        cases = build()
    body = ",\n".join("  " + json.dumps(c, separators=(",", ":")) for c in cases)
    OUT.write_text(f"[\n{body}\n]\n")
    ops: dict[str, int] = {}
    for c in cases:
        ops[c["op"]] = ops.get(c["op"], 0) + 1
    print(f"wrote {OUT} — {len(cases)} cases {ops}")


if __name__ == "__main__":
    main()

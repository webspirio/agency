#!/usr/bin/env python3
"""Regenerate packages/dec/golden.json from an INDEPENDENT reference.

    python3 packages/dec/scripts/gen-golden.py

WHY THIS IS NOT WRITTEN IN TYPESCRIPT.

The fixture this replaces was generated by importing `packages/dec/src/dec.ts`
and writing down whatever it returned, which made `golden.test.ts` an assertion
that dec equals dec. It could detect a CHANGE in dec; it could not detect dec
being WRONG. Proven: mutating `rescale` to `quotient + 1n` — half-up toward
+infinity instead of away from zero, the classic money bug the module's own
header claims to prevent — and regenerating with the old command left 675 of
675 rows green.

So every `expected` below is computed by CPython's `decimal` module, a
different implementation by different authors: arbitrary-precision decimal
arithmetic with explicit rounding modes, where dec uses scale-aligned bigint
integers. `ROUND_HALF_UP` in `decimal` means ties away from zero, which is
exactly dec's documented rule.

The generator does NOT import dec, and dec must never import this. Keeping it
in Python also keeps a second promise: the fixture cannot quietly drift back
into a tautology, because there is no way to reach dec from here.

THIRD AUTHORITY. `HAND_DERIVED` below transcribes literal expected values that
a human wrote out in reference/money/backend-money.spec.ts and
reference/money/frontend-decimal.test.ts. They are cited, never imported
(BUILD-PROMPT rule 7). Generation FAILS if CPython disagrees with any of them —
if that ever fires, fix the arithmetic, never the table.
"""

from __future__ import annotations

import json
import pathlib
from decimal import Decimal, ROUND_HALF_UP, localcontext

OUT = pathlib.Path(__file__).resolve().parent.parent / "golden.json"

# Wide enough that add/sub/mul are exact for every operand below (the largest
# product has 24 significant digits) and that a non-terminating quotient like
# 10/3 carries far more digits than any quantize target can double-round on.
PRECISION = 500


def fmt(value: Decimal, scale: int) -> str:
    """Render `value` at exactly `scale` fractional digits, dec's way.

    dec never emits a negative zero: `render` takes the sign from the bigint,
    which is 0n for '-0'. `decimal` does keep one, so it is dropped here. This
    is presentation of a value CPython computed, not arithmetic.
    """
    quantized = value.quantize(Decimal(1).scaleb(-scale), rounding=ROUND_HALF_UP)
    sign, digits, _exp = quantized.as_tuple()
    body = "".join(str(d) for d in digits).rjust(scale + 1, "0")
    rendered = body if scale == 0 else f"{body[:-scale]}.{body[-scale:]}"
    negative = sign == 1 and any(digits)
    return f"-{rendered}" if negative else rendered


def binary(op: str, a: str, b: str, scale: int) -> dict:
    x, y = Decimal(a), Decimal(b)
    result = {"add": x + y, "sub": x - y, "mul": x * y}[op]
    return {"op": op, "a": a, "b": b, "scale": scale, "expected": fmt(result, scale)}


def div(a: str, n: int, scale: int) -> dict:
    return {
        "op": "div",
        "a": a,
        "n": n,
        "scale": scale,
        "expected": fmt(Decimal(a) / Decimal(n), scale),
    }


def rnd(a: str, scale: int) -> dict:
    return {"op": "round", "a": a, "scale": scale, "expected": fmt(Decimal(a), scale)}


def summation(values: list[str], scale: int) -> dict:
    """Σ round(each line) — NOT round(Σ exact), and NOT a re-rounded running total.

    reference/money/backend-money.spec.ts:85-101 calls this distinction load
    bearing: the receipt prints each line and a total equal to the lines above
    it. Each value is quantized on its own; the already-rounded values are then
    added exactly.
    """
    total = sum(
        (Decimal(v).quantize(Decimal(1).scaleb(-scale), rounding=ROUND_HALF_UP) for v in values),
        Decimal(0),
    )
    return {"op": "sum", "values": values, "scale": scale, "expected": fmt(total, scale)}


def compare(a: str, b: str) -> dict:
    x, y = Decimal(a), Decimal(b)
    return {"op": "cmp", "a": a, "b": b, "expected": -1 if x < y else (1 if x > y else 0)}


def relation(op: str, a: str, b: str) -> dict:
    """gt/gte/lt/lte. Derived from cmp in dec, so the EQUALITY boundary is what
    matters: flipping gte to a strict > left all 690 tests green once."""
    x, y = Decimal(a), Decimal(b)
    expected = {"gt": x > y, "gte": x >= y, "lt": x < y, "lte": x <= y}[op]
    return {"op": op, "a": a, "b": b, "expected": expected}


def predicate(op: str, a: str) -> dict:
    x = Decimal(a)
    return {"op": op, "a": a, "expected": x == 0 if op == "isZero" else x < 0}



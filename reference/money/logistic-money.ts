import { roundEur } from '@/lib/economics'

/* ═══════════════════════════ гроші ═══════════════════════════

   Власник рахує в євро: ставку йому платять у євро, лізинг і страховка в євро,
   пальне на маршруті в євро. Гривня зʼявляється в одному місці — коли на
   українського замовника виставляється рахунок «по курсу, який ми вкажемо».

   Звідси єдине правило, на якому тримається вся арифметика: КУРС ШТАМПУЄТЬСЯ
   НА РЯДКУ. Оператор вписав 47,80 — це число лягає в рядок разом із сумою, і
   євровий еквівалент рахується ОДИН РАЗ, на записі. Далі його ніхто не
   перераховує.

   Інакше порівняння «за місяць, за рік, за 2» рухалося б щоразу, коли рухається
   гривня: минулий березень показував би сьогодні одну маржу, а завтра іншу, і
   власник перестав би вірити звіту — правильно перестав би.

   Округлення живе в ОДНІЙ функції на весь застосунок: `roundEur` з
   `@/lib/economics`, та сама, якою рахується кошторис рейсу. Якщо розкидати
   `Math.round` по файлах, сума рядків перестає збігатися з підсумком, і це
   видно на екрані першим.                                                     */

export type Currency = 'EUR' | 'UAH'

export interface Money {
  /** Сума в тій валюті, у якій її вписала людина. */
  amount: number
  ccy: Currency
  /**
   * Гривень за євро на момент запису. Для єврового рядка — 1: у нього немає
   * курсу, і вигадувати його нема з чого.
   */
  rate: number
  /**
   * Євровий еквівалент, порахований НА ЗАПИСІ й більше не перерахований.
   * Уся звітність складається саме з цього числа.
   */
  base: number
}

/** Курс, нижче якого це вже не курс, а порожнє поле у формі. */
const MIN_RATE = 0.000001

export { roundEur }

/**
 * Євровий рядок. Курс 1, бо переказувати нічого: замовник платить у євро.
 */
export function eurMoney(amount: number): Money {
  const value = roundEur(amount)
  return { amount: value, ccy: 'EUR', rate: 1, base: value }
}

/**
 * Гривневий рядок за курсом, який вписала людина. Курс лягає в рядок, і
 * `base` після цього — історія, а не похідна від сьогоднішнього курсу.
 *
 * Курс нуль або відʼємний — це не «безкоштовно», а незаповнене поле: сума
 * лишається, євровий еквівалент нуль, і такий рядок видно на екрані як
 * некласифікований.
 */
/**
 * Курс, який форма підставляє в гривневе поле за замовчуванням.
 *
 * Живе тут, а не двома літералами у двох формах: обидві підставляють ТЕ САМЕ
 * число, і розійшовшись, вони дали б два різні євро за той самий чек. Це
 * стартове значення поля, а не курс розрахунку — на рядок штампується те, що
 * оператор бачив на екрані в цю хвилину.
 */
export const DEMO_UAH_PER_EUR = 47.8

export function uahMoney(amount: number, rate: number): Money {
  const value = roundEur(amount)
  if (!Number.isFinite(rate) || rate < MIN_RATE) {
    return { amount: value, ccy: 'UAH', rate: 0, base: 0 }
  }
  return { amount: value, ccy: 'UAH', rate, base: roundEur(value / rate) }
}

/**
 * Сума в євро — те, з чого складається будь-який звіт.
 *
 * Читається `base`, а не `amount`: у гривневого рядка `amount` це гривні, і
 * додати їх до євро означало б скласти 2 000 € з 85 000 ₴ і отримати 87 000
 * «чогось».
 */
export function baseEur(m: Money): number {
  return Number.isFinite(m.base) ? m.base : 0
}

/** Підсумок списку. Порядок доданків фіксований, щоб сума не «дихала». */
export function sumEur(rows: { amount: Money }[]): number {
  let total = 0
  for (const r of rows) total += baseEur(r.amount)
  return roundEur(total)
}

/**
 * Гривневий стовпець поруч з євровим.
 *
 * Гривня НЕ є режимом звіту: у єврового рядка немає курсу, і вигадати його —
 * означало б порушити те саме правило штампованого курсу. Тому єврові рядки в
 * гривневому стовпці дають нуль, і поруч завжди стоїть євро.
 */
export function uahOf(m: Money): number {
  return m.ccy === 'UAH' ? m.amount : 0
}

/** Чи має рядок штампований курс — тобто чи можна йому вірити в історії. */
export function hasStampedRate(m: Money): boolean {
  return m.ccy === 'EUR' ? m.rate === 1 : m.rate >= MIN_RATE
}
